/** Renderiza una palabra como un solo sprite. Devuelve null si falta un glifo. */
fun textoPixel(palabra: String, color: Color): PixelSprite? {
    val glifos = palabra.uppercase().map { LETRAS[it] ?: return null }
    val pal = mapOf('A' to color)
    val filas = glifos.map { it.trimIndent().lines().filter(String::isNotBlank) }
    val alto = filas.maxOf { it.size }
    val sep = 1
    val ancho = filas.sumOf { f -> f.maxOf { it.length } } + sep * (filas.size - 1)

    val lienzo = MutableList(alto) { StringBuilder() }
    filas.forEachIndexed { i, glifo ->
        val w = glifo.maxOf { it.length }
        for (y in 0 until alto) {
            lienzo[y].append((glifo.getOrNull(y) ?: "").padEnd(w, '.'))
            if (i < filas.size - 1) lienzo[y].append(".".repeat(sep))
        }
    }
    return PixelSprite.of(lienzo.joinToString("\n") { it.toString() }, pal)
}
