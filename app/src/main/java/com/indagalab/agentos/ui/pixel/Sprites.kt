class Personaje(
    camiseta: Color,
    piel: Color = PIEL,
    pelo: Color = PELO,
) {
    private val pal = paletaPersonaje(camiseta, piel, pelo)
    val idle = PixelSprite.of(IDLE, pal)
    val walkA = PixelSprite.of(WALK_A, pal)
    val walkB = PixelSprite.of(WALK_B, pal)
    val workA = PixelSprite.of(WORK_A, pal)
    val workB = PixelSprite.of(WORK_B, pal)
    val sleep = PixelSprite.of(SLEEP, pal)
    val dead = PixelSprite.of(DEAD, pal)
    // Fuera de la oficina cada uno hace algo distinto: verlos a todos en la
    // misma postura era lo que hacía que la sala de descanso pareciera un
    // error de dibujado y no un sitio donde pasa algo.
    val juegaA = PixelSprite.of(JUEGA_A, pal)
    val juegaB = PixelSprite.of(JUEGA_B, pal)
    val tumbado = PixelSprite.of(TUMBADO, pal)
    val nadaA = PixelSprite.of(NADA_A, pal)
    val nadaB = PixelSprite.of(NADA_B, pal)
    val bailaA = PixelSprite.of(BAILA_A, pal)
    val bailaB = PixelSprite.of(BAILA_B, pal)
}

