/** Oscurece un color para usarlo como sombra. */
private fun Color.sombra(f: Float = 0.72f) = Color(red * f, green * f, blue * f, alpha)

private fun paletaPersonaje(
    camiseta: Color,
    piel: Color = PIEL,
    pelo: Color = PELO,
) = mapOf(
    'o' to NEGRO,          // contorno: solo la silueta exterior
    'O' to NEGRO,
    'H' to pelo,
    'S' to piel,
    's' to piel.sombra(0.82f),       // sombra de piel: da volumen a la cara
    'E' to OJO,
    'C' to camiseta,
    'c' to camiseta.sombra(),
    'R' to SILLA,
    'L' to LAPTOP_TAPA,
    'G' to LAPTOP_PANTALLA,
    'P' to PANTALON,
    'B' to ZAPATO,
    'X' to APAGADO,        // todo lo que está fuera de servicio
)

