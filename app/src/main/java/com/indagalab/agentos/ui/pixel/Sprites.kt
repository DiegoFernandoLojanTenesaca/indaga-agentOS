/**
 * Oficio por defecto según el nombre del skill. Se acierta la mayoría de las
 * veces y evita que el usuario tenga que configurar los seis a mano.
 */
fun oficioPorNombre(nombre: String): Oficio {
    val n = nombre.lowercase()
    return when {
        "telefono" in n || "llamada" in n || "sms" in n -> Oficio.TELEFONO
        "lista" in n || "archivo" in n || "doc" in n -> Oficio.CARPETA
        "nota" in n || "diario" in n || "escri" in n -> Oficio.LIBRETA
        "antirrobo" in n || "segur" in n || "vigil" in n -> Oficio.ESCUDO
        "web" in n || "busca" in n || "internet" in n -> Oficio.GLOBO
        "agenda" in n || "record" in n || "calend" in n -> Oficio.CALENDARIO
        else -> Oficio.TAZA
    }
}

