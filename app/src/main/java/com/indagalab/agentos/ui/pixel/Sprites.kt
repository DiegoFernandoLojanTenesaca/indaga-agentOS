/**
 * El arte de la sala, escrito como texto.
 *
 * Convención de caracteres:
 *   .  transparente      O  contorno (negro)     S  piel
 *   H  pelo              C  camiseta (color del skill)
 *   P  pantalón          B  zapatos              E  blanco del ojo
 *   D  madera oscura     W  madera clara         G  pantalla/cristal
 *   L  luz / brillo      A  acento (naranja Indaga)
 *
 * El color de camiseta NO está fijado aquí: `personaje(color)` lo inyecta, así
 * cada skill tiene el suyo sin duplicar el arte.
 */

